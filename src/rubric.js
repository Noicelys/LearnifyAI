const BY_KEY = new Map(DIMENSIONS.map((d) => [d.key, d]));

const byKey = (key) => BY_KEY.get(key) || null;

// น้ำหนักคะแนนรวม — typhoon.js ดึงไปใช้ ไม่ประกาศซ้ำที่นั่น
const WEIGHTS = Object.fromEntries(DIMENSIONS.map((d) => [d.key, d.weight]));

/**
 * ระดับที่คะแนนนี้ตกอยู่ พร้อมระดับถัดไปที่ต้องไปให้ถึง
 *
 * ⚠ คืน "ข้อความระดับ" เท่านั้น ไม่คืนตัวเลขออกไป — ผลลัพธ์ของฟังก์ชันนี้ถูกฝัง
 * ลงในคำแนะนำที่ส่งให้นักเรียนอ่านเอง ซึ่งเป็นหน้าที่ห้ามมีคะแนนโผล่ (ดู server.js)
 */
function standingOf(key, score) {
  const dim = byKey(key);
  if (!dim || !Number.isFinite(score)) return null;

  const idx = dim.bands.findIndex((b) => score >= b.min && score <= b.max);
  if (idx === -1) return null;

  const current = dim.bands[idx];
  const next = dim.bands[idx + 1] || null;

  return {
    dimension: dim.key,
    label: dim.label,
    why: dim.why,
    bandLabel: current.label,
    bandDesc: current.desc,
    nextLabel: next?.label || null,
    nextDesc: next?.desc || null,
    atTop: !next,
  };
}

// ── ประกอบข้อความเกณฑ์ให้ prompt ของตัวตรวจ ─────────────────
// รูปแบบต้องอ่านง่ายสำหรับโมเดล: หัวข้อ → ช่วงคะแนน → เพดานบังคับ
function renderRubricForPrompt() {
  return DIMENSIONS.map((d, i) => {
    const lines = [`${i + 1}. ${d.key} — ${d.promptHeading}`];
    if (d.promptNote) lines.push(`   ${d.promptNote}`);
    for (const b of d.bands) lines.push(`   ${b.min}-${b.max} ${b.desc}`);
    for (const c of d.caps) lines.push(`   เพดานบังคับ: ${c}`);
    return lines.join("\n");
  }).join("\n\n");
}

/**
 * โครงประโยคของด้านนั้น — เลือกแบบคงที่ตาม seed เพื่อให้กดดูงานเดิมซ้ำได้ผลเดิม
 * แต่คนที่ติดด้านเดียวกันหลายรอบจะไม่เจอโครงเดิมทุกครั้ง
 */
function frameFor(key, seedText = "") {
  const dim = byKey(key);
  if (!dim?.frames?.length) return null;

  let sum = 0;
  for (const ch of String(seedText)) sum = (sum + ch.charCodeAt(0)) % 9973;
  return dim.frames[sum % dim.frames.length];
}

function frameById(id) {
  for (const d of DIMENSIONS) {
    const f = (d.frames || []).find((x) => x.id === id);
    if (f) return { ...f, dimension: d.key };
  }
  return null;
}

/**
 * ประกอบประโยคตัวอย่างจากโครง + ค่าที่เติมได้
 * ช่องที่ไม่มีค่า (หรือเติมมาแล้วตรวจไม่ผ่าน) กลายเป็นเส้นว่างให้นักเรียนเติมเอง
 * ซึ่งตรงกับเจตนา — ส่วนที่ระบบยืนยันไม่ได้ ห้ามเดาแทนเขา
 */
const BLANK = "______";

function renderFrame(frame, values = {}) {
  if (!frame) return "";
  return frame.template.replace(/\{([^}]+)\}/g, (_, slot) => {
    const v = String(values[slot] || "").trim();
    return v || BLANK;
  });
}

